# ---- 2) 给 topic_map.md 大点表加考察频率列（幂等：已加则跳过，避免重复运行时损坏分隔行） ----
tp = os.path.join(base, "topic_map.md")
txt = open(tp, encoding="utf-8").read()
if "| 知识大点ID | 名称 | 章节 | 考察频率 | 前置知识大点ID |" not in txt:
    # 表头
    txt = txt.replace("| 知识大点ID | 名称 | 章节 | 前置知识大点ID |",
                      "| 知识大点ID | 名称 | 章节 | 考察频率 | 前置知识大点ID |")
    txt = txt.replace("|---|---|---|---|", "|---|---|---|---|---|")
    # 每一行大点：在"第X章"后插入频率
    def add_freq(m):
        kp = m.group(1)
        f = FREQ.get(kp, "中")
        return f"| {kp} | {m.group(2)} | {m.group(3)} | {f} | {m.group(4)} |"
    txt = re.sub(r"^\|\s*(CH\d+-\d\d)\s*\|\s*([^|]+)\s*\|\s*([^|]+)\s*\|\s*([^|]+)\s*\|$",
                 add_freq, txt, flags=re.M)
    open(tp, "w", encoding="utf-8").write(txt)
    print("topic_map.md 大点表已加考察频率列")
else:
    print("topic_map.md 大点表已含考察频率列，跳过")
